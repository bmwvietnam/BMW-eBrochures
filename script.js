    const brochureGroups = [
      { id: "models", heading: "CÁC MẪU XE BMW", items: vehicleBrochures },
      { id: "accessories", heading: "PHỤ TÙNG & PHỤ KIỆN", items: accessoryBrochures }
    ];
    const brochures = brochureGroups.flatMap(group => group.items);

    const title = document.getElementById("brochureTitle");
    const frame = document.getElementById("pdfFrame");
    const loading = document.getElementById("loading");
    const menuToggle = document.getElementById("menuToggle");
    const menu = document.getElementById("brochureMenu");
    const menuList = document.getElementById("brochureList");
    const backdrop = document.getElementById("menuBackdrop");
    let hasValidBrochure = false;

    function toDrivePreviewUrl(driveUrl) {
      try {
        const url = new URL(driveUrl);
        if (!["drive.google.com", "docs.google.com"].includes(url.hostname)) {
          throw new Error("Chỉ hỗ trợ link Google Drive");
        }
        const match = url.pathname.match(/\/file\/d\/([^/]+)/);
        const fileId = match ? match[1] : url.searchParams.get("id");
        if (!fileId) throw new Error("Không tìm thấy Google Drive file ID");
        return `https://drive.google.com/file/d/${encodeURIComponent(fileId)}/preview`;
      } catch (error) {
        console.error("Link brochure không hợp lệ:", driveUrl, error);
        return null;
      }
    }

    function getBrochureFromUrl() {
      const requestedId = new URLSearchParams(window.location.search).get("brochure");
      return brochures.find(item => item.id === requestedId) || brochures[0];
    }

    // Tạo link trực tiếp cho từng brochure, giữ các URL parameters khác.
    function getBrochureHref(id) {
      const url = new URL(window.location.href);
      url.searchParams.set("brochure", id);
      return url.pathname + url.search + url.hash;
    }

    function updateBrochureUrl(id) {
      const url = new URL(window.location.href);
      if (url.searchParams.get("brochure") === id) return;
      url.searchParams.set("brochure", id);
      window.history.pushState({ brochure: id }, "", url.toString());
    }

    function updateActiveMenuItem(id) {
      menuList.querySelectorAll(".menu-item").forEach(link => {
        const active = link.dataset.brochureId === id;
        link.classList.toggle("active", active);
        if (active) link.setAttribute("aria-current", "page");
        else link.removeAttribute("aria-current");
      });
    }

    function loadBrochure(id) {
      const brochure = brochures.find(item => item.id === id);
      if (!brochure) return;

      title.textContent = brochure.title;
      document.title = `${brochure.title} | BMW Việt Nam`;
      frame.title = `${brochure.label} E-Brochure`;
      updateActiveMenuItem(id);
      const previewUrl = toDrivePreviewUrl(brochure.driveUrl);
      loading.classList.remove("hidden");
      if (!previewUrl) {
        hasValidBrochure = false;
        frame.removeAttribute("src");
        loading.textContent = "Không thể tải brochure: link Google Drive không hợp lệ.";
        return;
      }
      hasValidBrochure = true;
      loading.textContent = "Đang tải e-brochure…";
      if (frame.src !== previewUrl) frame.src = previewUrl;
      else loading.classList.add("hidden");
    }

    function setMenuOpen(open) {
      menuToggle.classList.toggle("is-open", open);
      menu.classList.toggle("is-open", open);
      backdrop.classList.toggle("is-open", open);
      menuToggle.setAttribute("aria-expanded", String(open));
      menuToggle.setAttribute("aria-label", open ? "Đóng menu chọn brochure" : "Mở menu chọn brochure");
      menu.inert = !open;
    }

    menuToggle.addEventListener("click", () => {
      setMenuOpen(menuToggle.getAttribute("aria-expanded") !== "true");
    });
    backdrop.addEventListener("click", () => setMenuOpen(false));
    document.addEventListener("keydown", event => {
      if (event.key === "Escape" && menuToggle.getAttribute("aria-expanded") === "true") {
        setMenuOpen(false);
        menuToggle.focus();
      }
    });

    brochureGroups.forEach(group => {
      const section = document.createElement("details");
      section.className = "menu-group";
      section.dataset.groupId = group.id;
      section.addEventListener("toggle", () => {
        if (!section.open) return;
        menuList.querySelectorAll(".menu-group").forEach(other => {
          if (other !== section) other.open = false;
        });
      });

      const heading = document.createElement("summary");
      heading.className = "menu-heading";
      heading.textContent = group.heading;
      section.appendChild(heading);

      const list = document.createElement("div");
      list.className = "menu-list";

      if (!group.items.length) {
        const emptyState = document.createElement("p");
        emptyState.className = "menu-empty";
        emptyState.textContent = "Brochure đang được cập nhật.";
        list.appendChild(emptyState);
      }

      group.items.forEach(brochure => {
        const link = document.createElement("a");
        link.className = "menu-item";
        link.href = getBrochureHref(brochure.id);
        link.textContent = brochure.label;
        link.dataset.brochureId = brochure.id;
        link.addEventListener("click", event => {
          if (event.button !== 0 || event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
          event.preventDefault();
          loadBrochure(brochure.id);
          updateBrochureUrl(brochure.id);
          setMenuOpen(false);
          menuToggle.focus();
        });
        list.appendChild(link);
      });

      section.appendChild(list);
      menuList.appendChild(section);
    });

    frame.addEventListener("load", () => {
      if (hasValidBrochure) loading.classList.add("hidden");
    });

    window.addEventListener("popstate", () => {
      const brochure = getBrochureFromUrl();
      if (brochure) loadBrochure(brochure.id);
      setMenuOpen(false);
    });

    if (brochures.length) {
      loadBrochure(getBrochureFromUrl().id);
    } else {
      loading.textContent = "Chưa có e-brochure nào.";
      menuToggle.disabled = true;
    }
